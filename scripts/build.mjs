/**
 * Build the browser half from `src/client/` into the one file the module
 * loader ships: `lib/client.js`.
 *
 * The loader contract is the only thing this script knows about the shell: a
 * file is a call to `window.__ModuleLoader__.load({ id, factory(require) })`,
 * and peer dependencies arrive through that `require`. Rollup rewrites the ESM
 * imports into one CommonJS body; the envelope below hands that body the
 * loader's `require` and returns `module.exports`.
 *
 * Rollup is deliberate: it edits only the import/export statements, so every
 * other line keeps the bytes it has in `src/`. A template literal that carries
 * a `\n` still carries a newline after the build, and the artifact stays
 * readable next to its source. Tree shaking is off for the same reason — this
 * code is already one entry, and nothing should quietly disappear from it.
 *
 *   node scripts/build.mjs          rewrite the artifact
 *   node scripts/build.mjs --verify build in memory and fail when the
 *                                   committed artifact would change
 *
 * Verification is what `npm test` runs first, so a source edit that was not
 * rebuilt fails before the behaviour suite does, and the pre-commit hook
 * catches an artifact edited by hand.
 */
import { rollup } from 'rollup'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const ROOT = new URL('..', import.meta.url)
const PACKAGE_ID = 'dsh-vim'
const SOURCE = 'src/client/index.js'
const OUTPUT = 'lib/client.js'

const HEADER = `/**
 * Generated by scripts/build.mjs from ${SOURCE} — do not edit this file.
 * Rebuild: npm run build
 */
`

/**
 * Wrap one rollup bundle in the `__ModuleLoader__.load` envelope.
 *
 * The bundle body resolves `require` lexically to the factory parameter, which
 * is how rollup's `require('react')` reaches the shell's loader. `module` and
 * `exports` are the CommonJS pair the CJS output writes to.
 */
function envelope(code) {
  return `${HEADER}window.__ModuleLoader__.load({
  id: '${PACKAGE_ID}',
  factory(require) {
    const module = { exports: {} }
    const exports = module.exports
${code.trimEnd()}
    return module.exports
  },
})
`
}

/**
 * Compile the entry in memory: no writes until it has built, so a failed build
 * cannot leave a half-written artifact on disk.
 * @returns {Promise<string>} the artifact to write.
 */
async function compile() {
  const bundle = await rollup({
    input: fileURLToPath(new URL(SOURCE, ROOT)),
    // React is the shell's, not ours: the loader supplies it.
    external: ['react'],
    // Nothing in this code is dead, and a function reached only through a
    // render or a callback must not be shaken out.
    treeshake: false,
    onwarn(warning, warn) {
      // An import typo must not silently become a runtime `require`.
      if (warning.code === 'UNRESOLVED_IMPORT') {
        throw new Error(`build: unresolved import in ${SOURCE}: ${warning.message}`)
      }
      // Modules are layers, not a web: a cycle means two files own one seam.
      if (warning.code === 'CIRCULAR_DEPENDENCY') {
        throw new Error(`build: circular dependency: ${warning.message}`)
      }
      warn(warning)
    },
  })
  try {
    const { output } = await bundle.generate({
      format: 'cjs',
      exports: 'named',
      // Keep the source's own `const`/`let` spelling.
      generatedCode: { constBindings: true },
    })
    return envelope(output[0].code)
  } finally {
    await bundle.close()
  }
}

/** Read the committed artifact, or undefined when it has never been built. */
async function readOutput() {
  try {
    return await readFile(new URL(OUTPUT, ROOT), 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') return undefined
    throw error
  }
}

const artifact = await compile()
const verify = process.argv.includes('--verify')

if (verify) {
  const committed = await readOutput()
  if (committed !== artifact) {
    console.error(`build: ${OUTPUT} is stale — run npm run build and commit the result`)
    process.exit(1)
  }
  console.log(`build: ${OUTPUT} is up to date`)
} else {
  await writeFile(new URL(OUTPUT, ROOT), artifact)
  console.log(`build: wrote ${OUTPUT}`)
}
